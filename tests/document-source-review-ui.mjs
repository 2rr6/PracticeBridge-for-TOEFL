import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import http from 'node:http';
import { chromium } from 'playwright';
import {projectDocumentLayout,mapDocumentFields} from '../src/document-layout.mjs';
const out = new URL('../test-results/t04/',import.meta.url);
await fs.mkdir(out,{recursive:true});
const server = http.createServer(async(req,res) => {
  if(['/component.mjs','/document-source-policy.mjs'].includes(req.url)) { res.setHeader('Content-Type','text/javascript');res.end(await fs.readFile(new URL('../public/'+(req.url==='/component.mjs'?'document-source-review.mjs':'document-source-policy.mjs'),import.meta.url))); }
  else res.end('<!doctype html><meta charset="utf-8"><main id="review"></main>');
});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
let browser;
try {
  browser=await chromium.launch({channel:process.env.PRACTICEBRIDGE_BROWSER_CHANNEL||'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1200,height:850}});
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  const payload={documentLayout:{blocks:[{id:'b1',name:'original.docx',page:null,paragraph:2,text:'<img src=x onerror=alert(1)> Do NOT open the door.',layoutState:'unknown'},{id:'b2',name:'original.docx',paragraph:3,text:'SECRET ANSWER'}],evidenceMap:{b1:{rawLines:[1]}}},fieldEvidence:[{path:'groups.0.questions.0.prompt',state:'known',blockIds:['b1']},{path:'groups.0.questions.0.answer',state:'known',blockIds:['b2']}],pack:{groups:[{questions:[{prompt:'Which door?',answer:'SECRET ANSWER'}]}]}};
  payload.pack.groups[0].questions[0].prompt=payload.documentLayout.blocks[0].text;
  await page.evaluate(async data=>{const {mountDocumentSourceReview}=await import('/component.mjs');window.mount=mountDocumentSourceReview;window.data=data;mount(document.querySelector('#review'),data);},payload);
  assert.equal(await page.locator('[data-source-field]').count(),0);
  assert.doesNotMatch(await page.locator('body').textContent(),/SECRET ANSWER/);
  await page.evaluate(()=>mount(document.querySelector('#review'),data,{author:true}));
  await page.locator('[data-source-field="groups.0.questions.0.prompt"]').click();
  assert.match(await page.locator('[data-source-pane]').textContent(),/第 2 段.*分页与精确布局未知/s);
  assert.match(await page.locator('[data-source-pane]').textContent(),/<img src=x onerror=alert\(1\)> Do NOT/);
  assert.equal(await page.locator('img,iframe,script[src]').count(),0);
  assert.equal(await page.locator('[data-source-field$=".answer"]').count(),0);
  await page.getByLabel('展开答案来源（会剧透）').check();
  await page.locator('[data-source-field$=".answer"]').click();
  assert.match(await page.locator('[data-source-pane]').textContent(),/SECRET ANSWER/);
  await page.getByLabel('展开答案来源（会剧透）').uncheck();
  assert.doesNotMatch(await page.locator('body').textContent(),/SECRET ANSWER/);
  await page.locator('[data-source-field$=".prompt"]').click();
  await page.screenshot({path:new URL('source-review-desktop.png',out).pathname.replace(/^\/(\w:)/,'$1'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:new URL('source-review-mobile.png',out).pathname.replace(/^\/(\w:)/,'$1'),fullPage:true});
  const pack={groups:[{questions:[{prompt:'Which door is open?',answer:'B',explanation:'Blue is the answer.',hiddenReference:'HIDDEN TRANSCRIPT'}]}]};
  const documentLayout=projectDocumentLayout([{name:'source.txt',kind:'text',text:'1. Which door is open?\nAnswer: B. Which door is open? Blue is the answer.\nHIDDEN TRANSCRIPT'}]);
  const fieldEvidence=mapDocumentFields(pack,documentLayout);
  fieldEvidence.push({path:'groups.0.questions.0.hiddenReference',state:'known',blockIds:[documentLayout.blocks.at(-1).id]});
  await page.evaluate(data=>mount(document.querySelector('#review'),data,{author:true}),{pack,documentLayout,fieldEvidence});
  await page.locator('[data-source-field$=".prompt"]').click();
  assert.equal(await page.getByLabel('展开答案来源（会剧透）').isChecked(),false);
  assert.match(await page.locator('[data-source-pane]').textContent(),/Which door is open/);
  assert.doesNotMatch(await page.locator('body').textContent(),/Answer: B|Blue is the answer|HIDDEN TRANSCRIPT/);
  assert.equal(await page.locator('[data-source-field$=".hiddenReference"]').count(),0);
  await page.getByLabel('展开答案来源（会剧透）').check();
  await page.locator('[data-source-field$=".prompt"]').click();
  assert.match(await page.locator('[data-source-pane]').textContent(),/Answer: B/);
  await page.locator('[data-source-field$=".hiddenReference"]').click();
  assert.match(await page.locator('[data-source-pane]').textContent(),/HIDDEN TRANSCRIPT/);
  await page.getByLabel('展开答案来源（会剧透）').uncheck();
  assert.doesNotMatch(await page.locator('body').textContent(),/Answer: B|Blue is the answer|HIDDEN TRANSCRIPT/);
  const mixedLayout=projectDocumentLayout([{name:'mixed.txt',text:'The red door\nis NOT open. Unclassified private answer tail.',kind:'text'}]);
  const mixedPack={groups:[{passage:'The red door is NOT open.',questions:[]}]};
  await page.evaluate(data=>mount(document.querySelector('#review'),data,{author:true}),{pack:mixedPack,documentLayout:mixedLayout,fieldEvidence:mapDocumentFields(mixedPack,mixedLayout)});
  await page.locator('[data-source-field$=".passage"]').click();
  assert.match(await page.locator('[data-source-pane]').textContent(),/The red door.*is NOT open\./s);
  assert.doesNotMatch(await page.locator('body').textContent(),/Unclassified private answer tail/);
  await page.getByLabel('展开答案来源（会剧透）').check();
  await page.locator('[data-source-field$=".passage"]').click();
  assert.match(await page.locator('[data-source-pane]').textContent(),/Unclassified private answer tail/);
  console.log('PASS source review component: author gate, answer gate, field navigation, DOCX uncertainty, inert text, mobile width');
}finally{await browser?.close();await new Promise(resolve=>server.close(resolve));}
